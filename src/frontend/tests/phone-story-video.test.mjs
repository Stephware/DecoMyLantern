import {test} from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read = file => readFileSync(new URL('../' + file, import.meta.url), 'utf8')

test('device MP4 exports use the exact existing deterministic StoryFrame and timings', () => {
  const source = read('src/features/story/phoneStoryVideo.ts')
  const spec = read('src/features/story/storySpec.ts')
  assert.match(source, /createElement\(StoryFrame, \{data, frame\}\)/)
  assert.match(source, /renderToStaticMarkup/)
  assert.match(source, /frame < STORY_FRAMES; frame\+\+/)
  assert.match(source, /source\.add\(frame \/ STORY_FPS, 1 \/ STORY_FPS\)/)
  assert.match(spec, /STORY_FPS = 30/)
  assert.match(spec, /STORY_FRAMES = 240/)
  assert.match(spec, /STORY_WIDTH = 1080/)
  assert.match(spec, /STORY_HEIGHT = 1920/)
  assert.match(source, /quality: new Quality\('high'\)/)
  assert.match(source, /codec: 'avc'/)
  assert.match(source, /new Mp4OutputFormat\(\)/)
  assert.match(source, /type:'video\/mp4'/)
  assert.match(source, /result\.slice\(4, 8\)\.text\(\) !== 'ftyp'/)
})

test('phone encoder is never assumed and unsupported browsers safely use server', () => {
  const phone = read('src/features/story/phoneStoryVideo.ts')
  const share = read('src/features/story/StoryShare.tsx')
  assert.match(phone, /isPhoneStoryDevice\(\)/)
  assert.match(phone, /max-width: 900px/)
  assert.match(phone, /window\.isSecureContext/)
  assert.match(phone, /typeof VideoEncoder === 'undefined'/)
  assert.match(phone, /canEncodeVideo\('avc'/)
  assert.match(phone, /return false/)
  assert.match(share, /import\('\.\/phoneStoryVideo'\)/)
  assert.match(share, /module\.canRenderStoryOnPhone\(\)/)
  assert.match(share, /Generate on this phone/)
  assert.match(share, /Generate in background instead/)
  assert.match(share, /const job = await startOwnerVideoJob\(controller\.signal\)/)
  assert.match(share, /phoneFailed = true/)
  assert.match(share, /request\.mode = 'server'/)
  assert.match(share, /setVideoJobRefresh\(n => n \+ 1\)/)
  assert.match(share, /getOwnerVideoJobStatus\(controller\.signal\)/)
  assert.match(share, /getOwnerVideoJobFile\(controller\.signal\)/)
})

test('phone render is bounded, cancelable and never claims to survive a closed tab', () => {
  const phone = read('src/features/story/phoneStoryVideo.ts')
  const share = read('src/features/story/StoryShare.tsx')
  assert.match(phone, /MAX_PHONE_RENDER_MS = 120_000/)
  assert.match(phone, /signal\.aborted \|\| document\.hidden/)
  assert.match(phone, /await nextPaint\(signal\)/)
  assert.match(phone, /await output\.cancel\(\)\.catch/)
  assert.match(phone, /await image\.decode\(\)/)
  assert.match(phone, /getImageData\(/)
  assert.match(phone, /URL\.revokeObjectURL\(blobUrl\)/)
  assert.match(share, /current\.controller\.abort\(\)/)
  assert.match(share, /Phone generation stopped/)
  assert.match(share, /Keep this page open/)
  assert.match(share, /latestDataKey\.current !== requestedKey/)
})

test('dependency is pinned and phone MP4 remains separate from Story PNG, guests, and 3x zoom', () => {
  const packageJson = JSON.parse(read('package.json'))
  const lock = JSON.parse(read('package-lock.json'))
  const share = read('src/features/story/StoryShare.tsx')
  const guest = read('src/features/invitations/GuestInvitationPage.tsx')
  assert.equal(packageJson.dependencies.mediabunny, '1.65.0')
  assert.equal(lock.packages[''].dependencies.mediabunny, '1.65.0')
  assert.equal(lock.packages['node_modules/mediabunny'].version, '1.65.0')
  assert.ok(lock.packages['node_modules/@types/dom-webcodecs'])
  assert.ok(!guest.includes('<StoryShare'))
  assert.match(share, /exportStoryMedia\(data\.kind, 'png', token, controller\.signal\)/)
  assert.match(share, /exportStoryMedia\(data\.kind, 'mp4', token, controller\.signal\)/)
  assert.match(share, /Download MP4/)
  assert.match(share, /Share video/)
})
