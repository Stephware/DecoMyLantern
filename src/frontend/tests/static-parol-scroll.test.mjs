test('landing shimmer stays decorative, has no image movement and respects reduced motion', () => {
  const welcome = read('src/features/owner/WelcomePage.tsx')
  const css = read('src/styles/index.css')
  assert.ok(welcome.includes('src="/api/designs/classic/showcase?v=v1"'))
  assert.ok(welcome.includes("event.currentTarget.src = '/parol-classic-preview.svg'"))
  assert.match(welcome, /<img[^>]*src="\/api\/designs\/classic\/showcase\?friends=20&v=v2"/)
  assert.ok(welcome.includes('draggable={false}'))
  assert.ok(welcome.includes('className="welcome-parol-artwork pointer-events-none block h-auto w-full select-none"'))
  assert.ok(welcome.includes('className="relative mx-auto w-full max-w-[710px] p-6 sm:p-8"'))
  assert.ok(welcome.includes('className="pointer-events-none absolute inset-0 overflow-visible"'))
  assert.ok(welcome.includes('className="welcome-parol-halo absolute inset-[10%]"'))
  assert.match(css, /@keyframes welcome-parol-halo-pulse/)
  assert.match(css, /@keyframes welcome-parol-twinkle/)
  assert.match(css, /@keyframes welcome-parol-light-breathe/)
  assert.match(css, /\.welcome-parol-halo \{/)
  assert.match(css, /\.welcome-parol-glint \{/)
  assert.equal((css.match(/\.welcome-parol-glint:nth-child\(/g) ?? []).length, 8)
  assert.equal((css.match(/\.welcome-parol-sparkle:nth-child\(/g) ?? []).length, 2)
  // Most glints follow the ornaments and only two stay beyond the parol.
  assert.ok(css.includes('left: 50%; top: 25%'))
  assert.ok(css.includes('left: 75%; top: 49%'))
  assert.ok(css.includes('left: 26%; top: 47%'))
  assert.ok(css.includes('left: 10%; top: 13%'))
  assert.ok(css.includes('left: 89%; top: 86%'))
  assert.ok(css.includes('rgba(255, 211, 111, .18)'))
  assert.ok(css.includes('rgba(255, 197, 105, .07)'))
  assert.ok(css.includes('@media (prefers-reduced-motion: reduce)'))
  assert.ok(css.includes('.welcome-parol-halo { animation: none !important;'))
  assert.ok(css.includes('.welcome-parol-glint, .welcome-parol-sparkle { animation: none !important;'))
  assert.ok(css.includes('.welcome-parol-artwork { animation: none !important; filter: none !important;'))
  // The image illumination changes but the image never translates or scales.
  assert.ok(css.includes('animation: welcome-parol-light-breathe 5.8s'))
  assert.ok(css.includes('transform: none;'))
  assert.doesNotMatch(css, /\.welcome-parol-artwork[^\n]*translate\(/)
  assert.doesNotMatch(welcome, /<LanternScene|onPointerDown=|onWheel=|onTouchMove=/)
})
