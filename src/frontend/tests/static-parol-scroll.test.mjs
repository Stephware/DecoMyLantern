test('welcome shimmer stays outside the parol, noninteractive, and reduced-motion safe', () => {
  const welcome = read('src/features/owner/WelcomePage.tsx')
  const css = read('src/styles/index.css')
  assert.ok(welcome.includes('src="/api/designs/classic/showcase?friends=20&v=v2"'))
  assert.ok(welcome.includes("event.currentTarget.src = '/parol-classic-preview.svg'"))
  assert.ok(welcome.includes('draggable={false}'))
  assert.ok(welcome.includes('className="welcome-parol-artwork pointer-events-none relative z-10 block h-auto w-full select-none"'))
  assert.ok(welcome.includes('welcome-parol-stage relative mx-auto w-full max-w-[710px] p-6 sm:p-8'))
  assert.ok(welcome.includes('className="welcome-parol-decor pointer-events-none absolute inset-0 z-20"'))
  assert.doesNotMatch(welcome, /welcome-parol-glint|welcome-parol-sparkle|welcome-parol-front-lights/)
  assert.match(css, /@keyframes welcome-parol-ambient-pulse/)
  assert.match(css, /@keyframes welcome-parol-twinkle/)
  assert.match(css, /@keyframes welcome-parol-dust-float/)
  assert.match(css, /\.welcome-parol-ambient \{/)
  assert.equal((css.match(/\.welcome-parol-starburst:nth-child\(/g) ?? []).length, 4)
  assert.equal((css.match(/\.welcome-parol-dust:nth-child\(/g) ?? []).length, 10)
  // Keep glints in the empty outer margin, never across the lantern ornaments.
  const positions = [...css.matchAll(/\.welcome-parol-(?:starburst|dust):nth-child\(\d+\)\s*\{ left: (\d+)%; top: (\d+)%/g)]
  assert.equal(positions.length, 14)
  assert.ok(positions.every(([, x, y]) => Number(x) <= 10 || Number(x) >= 90 || Number(y) <= 9 || Number(y) >= 90))
  assert.ok(css.includes('@media (prefers-reduced-motion: reduce)'))
  assert.ok(css.includes('.welcome-parol-ambient { animation: none !important;'))
  assert.ok(css.includes('.welcome-parol-starburst, .welcome-parol-dust { animation: none !important;'))
  assert.ok(css.includes('.welcome-parol-artwork { animation: none !important; filter: none !important;'))
  assert.ok(css.includes('transform: none;'))
  assert.doesNotMatch(welcome, /<LanternScene|onPointerDown=|onWheel=|onTouchMove=/)
})
