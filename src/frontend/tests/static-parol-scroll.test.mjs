import {test} from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read = relativePath => readFileSync(new URL('../' + relativePath, import.meta.url), 'utf8')

test('welcome page alone uses an approved static, non-draggable parol image', () => {
  const welcome = read('src/features/owner/WelcomePage.tsx')
  const asset = read('public/parol-classic-preview.svg')
  const downtime = read('../../downtime/index.html')
  const showcase = read('../../src/backend/DecoMyLantern.Api/Controllers/DesignShowcaseController.cs')
  assert.ok(welcome.includes('src="/api/designs/classic/showcase?friends=20&v=v2"'))
  assert.ok(welcome.includes("event.currentTarget.src = '/parol-classic-preview.svg'"))
  assert.ok(welcome.includes('alt="Classic Gold festival parol with 20 sample friends"'))
  assert.ok(showcase.includes('var previewFriendCount = friends ?? 50'))
  assert.ok(showcase.includes('SupportsFriendCount(friends)'))
  assert.ok(showcase.includes('friends is null or 20 or 50'))
  assert.ok(showcase.includes('friendCount = previewFriendCount'))
  assert.ok(showcase.includes('Enumerable.Range(0, previewFriendCount).ToArray()'))
  assert.ok(showcase.includes('patternKey = "default"'))
  assert.ok(showcase.includes('Response.Headers.CacheControl = "public, max-age=86400"'))
  assert.ok(!showcase.includes('GetAcceptedLights'))
  assert.ok(welcome.includes('draggable={false}'))
  assert.ok(welcome.includes('pointer-events-none'))
  assert.ok(welcome.includes('welcome-parol-ambient'))
  assert.equal((welcome.match(/className="welcome-parol-starburst"/g) ?? []).length, 4)
  assert.equal((welcome.match(/className="welcome-parol-dust"/g) ?? []).length, 10)
  assert.equal((welcome.match(/className="welcome-parol-bokeh welcome-parol-bokeh-/g) ?? []).length, 3)
  assert.ok(welcome.includes('aria-hidden="true"'))
  assert.ok(!welcome.includes('onPointerDown='))
  assert.ok(!welcome.includes('onTouchMove='))
  assert.ok(!welcome.includes('onWheel='))
  assert.ok(!welcome.includes('setCamera('))
  assert.ok(!welcome.includes('<LanternScene'))
  assert.ok(!welcome.includes('LegacyLanternPreview'))
  assert.ok(!welcome.includes('previewCount={5}'))
  assert.match(asset, /^<svg xmlns="http:\/\/www.w3.org\/2000\/svg"/)
  assert.match(asset, /data-design="classic" data-friends="0"/)
  assert.ok(downtime.includes(asset.trim()), 'fallback image must reuse approved Classic Gold parol')
  assert.doesNotMatch(asset, /<script\b|<animate\b|onpointer|ontouch|http[s]?:\/\/(?!www\.w3\.org\/2000\/svg)/)
})

